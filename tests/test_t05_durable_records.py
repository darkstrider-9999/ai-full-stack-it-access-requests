"""T05: durable current/history records and generation-consistent deliverables.

Business expectations come from B001–B020, not output generated by the app.
All state/output is temporary; provider replies are saved offline fixtures.
Reuse, replay, durable worker claims and overlapping intake belong to T06–T14.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from threading import Event
from unittest import mock

from support.offline_guard import install
from access_intake.providers import MockProvider
from access_intake.review import prepare_review
from access_intake.sources import load_source

install()
ROOT = Path(__file__).resolve().parents[1]
MOCKS = ROOT / "tests/mock_responses"
EXPECTED = json.loads((ROOT / "tests/expected/step4.json").read_text())["cases"]
CONFIG = {"provider": "mock", "prompt_version": "access-extraction-v2", "output_limit": 4096}
POLICY_HASH = hashlib.sha256((ROOT / "materials/office-policy.md").read_bytes()).hexdigest()
MANDATORY = {
    "document_id", "source_sha256", "attempt_id", "extraction", "status", "owner",
    "next_action", "error", "response_source", "configuration", "policy_hash", "processing_state",
}


class T05DurableRecords(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)
        self.state = self.directory / "state.sqlite3"

    def open_store(self):
        from access_intake.storage import Store

        return Store(self.state)

    def commit_source(self, store, number, *, path=None, fixture=None):
        source = load_source(path or ROOT / "materials/requests" / f"IT-{number:03}.json")
        provider = MockProvider(MOCKS, script=[{"response": fixture or f"it-{number:03}.json"}])
        attempt = store.register(source, configuration=CONFIG, policy_hash=POLICY_HASH)
        record = prepare_review(source, provider, attempt_id=attempt, configuration=CONFIG)
        store.complete(attempt, record)
        self.assertEqual(provider.call_count, 1)
        return source, attempt, record

    def assert_record(self, record, number):
        expected = EXPECTED[f"B{number:03}"]
        self.assertTrue(MANDATORY <= record.keys())
        self.assertEqual(record["document_id"], f"IT-{number:03}.json")
        raw = (ROOT / "materials/requests" / record["document_id"]).read_bytes()
        self.assertEqual(record["source_sha256"], hashlib.sha256(raw).hexdigest())
        self.assertTrue(record["attempt_id"])
        self.assertEqual(record["configuration"], CONFIG)
        self.assertEqual(record["policy_hash"], POLICY_HASH)
        self.assertEqual(record["processing_state"], "succeeded")
        self.assertEqual(tuple(record[key] for key in ("status", "owner", "next_action")), tuple(expected["route"]))
        self.assertIsNone(record["error"])
        self.assertEqual(record["response_source"], "mock")
        for field, value in expected["facts"].items():
            self.assertEqual(record["extraction"][field], value, field)
        self.assertEqual(record["extraction"]["supporting_quotes"], [json.loads(raw)["message"]])
        self.assertNotIn("raw_bytes", record, "source snapshots belong outside current exports")
        self.assertNotEqual(record["status"], "approved")

    def read_pair(self, generation):
        records = [json.loads(line) for line in (generation / "extractions.jsonl").read_text(encoding="utf-8").splitlines()]
        queue = json.loads((generation / "queue.json").read_text(encoding="utf-8"))
        self.assertIsInstance(queue, list)
        by_document = {record["document_id"]: record for record in records}
        self.assertEqual(len(by_document), len(records), "duplicate current document")
        self.assertEqual({entry["document_id"] for entry in queue}, set(by_document))
        self.assertEqual(len(queue), len(records))
        for entry in queue:
            record = by_document[entry["document_id"]]
            for field in ("attempt_id", "source_sha256", "status", "owner", "next_action", "generation_id"):
                self.assertEqual(entry[field], record[field], field)
            self.assertEqual(record["generation_id"], generation.name)
        return records, queue

    def cli(self, *arguments):
        result = subprocess.run([
            sys.executable, "-m", "access_intake", *map(str, arguments), "--state", str(self.state),
        ], cwd=ROOT, text=True, capture_output=True, timeout=30)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout

    def test_t05_twenty_current_records_survive_reopen_with_archived_sources(self):
        with self.open_store() as store:
            attempts = []
            for number in range(1, 21):
                _, attempt, _ = self.commit_source(store, number)
                attempts.append(attempt)
            self.assertEqual(len(set(attempts)), 20)

        with self.open_store() as reopened:
            records = reopened.current_records()
            self.assertEqual(len(records), 20)
            self.assertEqual({row["document_id"] for row in records}, {f"IT-{n:03}.json" for n in range(1, 21)})
            for record in records:
                number = int(record["document_id"][3:6])
                self.assert_record(record, number)
                history = reopened.history(record["document_id"])
                self.assertEqual(len(history), 1)
                archived = history[0]
                self.assertEqual(archived["attempt_id"], record["attempt_id"])
                self.assertEqual(archived["raw_bytes"], (ROOT / "materials/requests" / record["document_id"]).read_bytes())
                self.assertEqual(archived["configuration"], CONFIG)
                self.assertEqual(archived["policy_hash"], POLICY_HASH)
                self.assertEqual(archived["result"], record)

    def test_t05_completed_attempts_are_immutable_and_current_history_are_distinct(self):
        with self.open_store() as store:
            source, first, original = self.commit_source(store, 1)
            with self.assertRaises(ValueError):
                store.complete(first, {**original, "status": "approved"})
            # Register a second attempt at the storage boundary, without asserting
            # intake reuse or replay semantics reserved for step 6.
            _, second, _ = self.commit_source(store, 1)
            self.assertNotEqual(first, second)
            self.assertEqual(len(store.current_records()), 1)
            self.assertEqual(store.current_records()[0]["attempt_id"], second)
            rows = store.history(source.document_id)
            self.assertEqual([row["attempt_id"] for row in rows], [first, second])
            self.assertEqual(rows[0]["result"]["status"], "review")
            self.assertEqual(rows[0]["raw_bytes"], source.raw_bytes)
            self.assertIsNone(rows[0]["result"]["error"])

    def test_t05_equal_request_ids_do_not_merge_distinct_filenames(self):
        raw = (ROOT / "materials/requests/IT-001.json").read_bytes()
        left, right = self.directory / "left", self.directory / "right"
        left.mkdir()
        right.mkdir()
        first_path, second_path = left / "IT-001.json", right / "IT-002.json"
        first_path.write_bytes(raw)
        second_path.write_bytes(raw)
        with self.open_store() as store:
            self.commit_source(store, 1, path=first_path)
            self.commit_source(store, 2, path=second_path, fixture="shared-request-id.json")
            records = {row["document_id"]: row for row in store.current_records()}
            self.assertEqual(set(records), {"IT-001.json", "IT-002.json"})
            self.assertEqual(len(store.history("IT-001.json")), 1)
            self.assertEqual(len(store.history("IT-002.json")), 1)
            for record in records.values():
                self.assertEqual(record["extraction"]["request_id"], "IT-001")
                self.assertEqual(record["source_sha256"], hashlib.sha256(raw).hexdigest())
            self.assertEqual(tuple(records["IT-001.json"][key] for key in ("status", "owner", "next_action")), ("review", "System Owner", "review-request"))
            second = records["IT-002.json"]
            self.assertEqual(tuple(second[key] for key in ("status", "owner", "next_action")), ("needs-information", "IT Service Desk", "clarify"))
            self.assertTrue(any("identifier mismatch" in issue for issue in second["extraction"]["issues"]))

    def test_t05_exports_pair_one_snapshot_and_keep_pinned_generations_readable(self):
        from access_intake.exports import export_generation

        output = self.directory / "deliverables"
        with self.open_store() as store:
            for number in range(1, 21):
                self.commit_source(store, number)
            generation = Path(export_generation(store, output)).resolve()
            records, _ = self.read_pair(generation)
            self.assertEqual(len(records), 20)
            self.assertEqual((output / "current").resolve(), generation)
            for name in ("extractions.jsonl", "queue.json"):
                self.assertEqual((output / name).resolve(), generation / name)
            for record in records:
                self.assert_record(record, int(record["document_id"][3:6]))
            # Export records must not include historical attempts as current rows.
            self.commit_source(store, 1)
            next_generation = Path(export_generation(store, output)).resolve()
            self.assertNotEqual(generation, next_generation)
            next_records, _ = self.read_pair(next_generation)
            self.assertEqual(len(next_records), 20)
            self.assertNotEqual(next(row for row in records if row["document_id"] == "IT-001.json")["attempt_id"], next(row for row in next_records if row["document_id"] == "IT-001.json")["attempt_id"])
            self.assertEqual(self.read_pair(generation)[0], records)

    def test_t05_export_publication_overlaps_intake_without_mixing_snapshots(self):
        from access_intake.exports import export_generation

        output = self.directory / "deliverables"
        entered, release = Event(), Event()
        original_replace = os.replace

        def held_replace(source, destination, *args, **kwargs):
            if Path(destination).resolve(strict=False) == (output / "current").resolve(strict=False) or Path(destination) == output / "current":
                entered.set()
                if not release.wait(timeout=10):
                    raise TimeoutError("test did not release publication barrier")
            return original_replace(source, destination, *args, **kwargs)

        with self.open_store() as store:
            self.commit_source(store, 1)
            old = Path(export_generation(store, output)).resolve()
            self.commit_source(store, 2)
            with mock.patch("os.replace", side_effect=held_replace), ThreadPoolExecutor(max_workers=1) as executor:
                future = executor.submit(export_generation, store, output)
                try:
                    self.assertTrue(entered.wait(timeout=5), "export never reached the generation-pointer swap")
                    self.assertFalse(future.done())
                    self.assertEqual((output / "current").resolve(), old)
                    self.assertEqual(len(self.read_pair(old)[0]), 1)
                    # A publication barrier must not hold the database transaction.
                    self.commit_source(store, 3)
                    self.assertEqual(len(store.current_records()), 3)
                finally:
                    release.set()
                published = Path(future.result(timeout=10)).resolve()
            self.assertEqual((output / "current").resolve(), published)
            records, _ = self.read_pair(published)
            self.assertEqual({row["document_id"] for row in records}, {"IT-001.json", "IT-002.json"})
            self.assertEqual(len(self.read_pair(old)[0]), 1)

    def test_t05_cli_intake_queue_inspect_history_and_export_share_durable_state(self):
        self.cli("intake", ROOT / "materials/requests", "--provider", "mock", "--mock-responses", MOCKS,
                 "--mock-script", MOCKS / "manifest-m20.json")
        records = json.loads(self.cli("queue", "--json"))
        self.assertEqual(len(records), 20)
        self.assertEqual({row["document_id"] for row in records}, {f"IT-{n:03}.json" for n in range(1, 21)})
        for record in records:
            expected = EXPECTED["B" + record["document_id"][3:6]]
            self.assertEqual(tuple(record[key] for key in ("status", "owner", "next_action")), tuple(expected["route"]))
            self.assertEqual(record["response_source"], "mock")
        record = json.loads(self.cli("inspect", "--document", "IT-001.json", "--json"))
        self.assertEqual(record["extraction"]["requester"], "Maya Chen")
        history = json.loads(self.cli("history", "--document", "IT-001.json", "--json"))
        self.assertEqual(len(history), 1)
        self.assertEqual(history[0]["attempt_id"], record["attempt_id"])
        display = self.cli("queue")
        for row in records:
            for field in ("document_id", "source_sha256", "attempt_id", "status", "owner", "next_action", "response_source"):
                self.assertIn(row[field], display)
        self.assertIn("human", display.casefold())
        output = self.directory / "cli-exports"
        self.cli("export", "--output", output)
        exported, _ = self.read_pair((output / "current").resolve())
        self.assertEqual(len(exported), 20)
        self.assertEqual({row["attempt_id"] for row in exported}, {row["attempt_id"] for row in records})
